class BananaFarm:
    def __init__(self, purchase_round, base_cost=1225):
        self.purchase_round = purchase_round
        self.tiers = [0, 0, 0]  # [Top Path, Middle Path, Bottom Path]
        self.total_invested = base_cost
        self.bank_balance = 0.0
        
        # Approximate cumulative/base upgrade costs for Medium difficulty
        self.upgrade_costs = {
            0: {1: 500, 2: 600, 3: 3000, 4: 19000, 5: 115000},     # Top path
            1: {1: 300, 2: 800, 3: 3650, 4: 7200, 5: 100000},     # Middle path
            2: {1: 250, 2: 400, 3: 2700, 4: 15000, 5: 70000}      # Bottom path
        }

    def upgrade(self, path, target_tier):
        """
        Upgrades the farm along a given path (0: Top, 1: Middle, 2: Bottom) to target_tier,
        enforcing BTD6 crosspathing rules:
        - Only ONE path can exceed Tier 2.
        - Maximum tier is 5.
        - Max of two active paths total.
        """
        if not (0 <= path <= 2):
            raise ValueError("Path must be 0 (Top), 1 (Middle), or 2 (Bottom).")
        if not (1 <= target_tier <= 5):
            raise ValueError("Tier must be between 1 and 5.")
            
        current_tier = self.tiers[path]
        if target_tier <= current_tier:
            raise ValueError("Target tier must be higher than current tier.")

        temp_tiers = list(self.tiers)
        cost_incurred = 0
        
        for t in range(current_tier + 1, target_tier + 1):
            temp_tiers[path] = t
            
            # BTD6 Crosspathing Validation Rules
            paths_above_2 = sum(1 for tr in temp_tiers if tr > 2)
            if paths_above_2 > 1:
                raise ValueError("Invalid crosspath: Only one path can exceed Tier 2 in BTD6.")
            
            paths_active = sum(1 for tr in temp_tiers if tr > 0)
            if paths_active > 2:
                raise ValueError("Invalid crosspath: BTD6 only allows a primary path and one crosspath.")

            cost_incurred += self.upgrade_costs[path][t]

        # Apply upgrades and record cost
        self.tiers = temp_tiers
        self.total_invested += cost_incurred
        return cost_incurred

    def get_round_income(self, round_num):
        """
        Calculates income generated by the farm based on its current tiers and crosspaths,
        handling standard production, automated marketplaces, and Bank interest.
        """
        top, mid, bot = self.tiers
        
        # Middle Path Tier 3+ (Bank Mechanics: accumulates cash and earns 15% interest)
        if mid >= 3:
            if mid == 3:  # Monkey Bank (e.g., 2-3-0)
                capacity = 9500
                production = 300 + (200 if top >= 2 else 0)
                self.bank_balance += production
                self.bank_balance += self.bank_balance * 0.15
                if self.bank_balance > capacity:
                    self.bank_balance = capacity
                return 0  # Banks store internally until collected/withdrawn
            elif mid == 4:  # IMF Loan
                capacity = 12500
                production = 600
                self.bank_balance += production
                self.bank_balance += self.bank_balance * 0.15
                if self.bank_balance > capacity:
                    self.bank_balance = capacity
                return 0

        # Production / Marketplace Farms
        top_incomes = {0: 80, 1: 200, 2: 320, 3: 720, 4: 2400, 5: 10000}
        income = top_incomes.get(top, 80)
        
        # Crosspathing modifiers
        if top >= 3 and mid == 2:
            income *= 1.25  # Valuable Bananas bonus
            
        # Bottom Path (Marketplaces)
        if bot >= 3:
            if bot == 3:  # Marketplace
                income = 300
                if mid == 2: income += 50
            elif bot == 4:  # Central Market
                income = 1000
            elif bot == 5:  # Monkey Wall Street
                income = 4000
                
        return income